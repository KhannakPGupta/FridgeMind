def seed_database():
    """Populate database with curated recipes if table is empty."""
    init_db()
    with get_db_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT COUNT(*) FROM recipes")
        count = cursor.fetchone()[0]
        if count == 0:
            logger.info("Seeding database with %d curated multi-cuisine recipes...", len(CURATED_RECIPES))
            for r in CURATED_RECIPES:
                cursor.execute("""
                    INSERT INTO recipes (
                        id, name, cuisine, time, difficulty, tags, desc, image,
                        cal, rating, accent, servings, ingredients, steps, step_timers,
                        substitution, tastes, effort
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    r["id"],
                    r["name"],
                    r["cuisine"],
                    r["time"],
                    r["difficulty"],
                    json.dumps(r["tags"]),
                    r["desc"],
                    r["image"],
                    r["cal"],
                    r["rating"],
                    r["accent"],
                    r["servings"],
                    json.dumps(r["ingredients"]),
                    json.dumps(r["steps"]),
                    json.dumps(r["step_timers"]),
                    r["substitution"],
                    json.dumps(r["tastes"]),
                    r["effort"],
                ))
            conn.commit()
            logger.info("Database successfully seeded.")
        else:
            logger.info("Database already contains %d recipes, skipping seed.", count)


if __name__ == "__main__":
    seed_database()
